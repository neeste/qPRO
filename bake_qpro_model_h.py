#!/usr/bin/env python3
"""
bake_qpro_model_h.py

Pre-bakes all acoustic, biophysical, and normative constants required by the
client-side C99 / WebAssembly qPRO clinical interpreter into:
  1. ``qpro_model.h`` — static C99 constant arrays (~14 KB, zero runtime file I/O)
  2. ``qpro_demo_cases.js`` — 6 anonymized qtest_dataset clinical demo cases
     (NH013, HL045, HL011, HL068, HL030, HL048) + normative metadata for the
     browser front-end.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
import numpy as np

SIM_DIR = Path(__file__).resolve().parent.parent / "qVCV" / "sim"
sys.path.insert(0, str(SIM_DIR))

from qvcv_biophysical_model import (  # noqa: E402
    ANSI_RETSPL_DB,
    AUD_FREQS_HZ,
    DEFAULT_QCLS_MAT,
    DEFAULT_STIMULI_DIR,
    REF_SNR_ARR,
    extract_vcv_acoustic_bank,
    load_qcls_cochlear_profiles,
)
from prototype_clinical_reports import (  # noqa: E402
    RETSPL_TABLES,
    build_clinical_norms,
    load_raw_qcls_elc_matrix_map,
)
from scipy.io import loadmat  # noqa: E402


def fmt_c_array_1d(arr: np.ndarray | list[float], fmt: str = "{:.6f}") -> str:
    vals = [fmt.format(float(x)) for x in np.asarray(arr, dtype=float).ravel()]
    lines = []
    for i in range(0, len(vals), 8):
        lines.append("    " + ", ".join(vals[i : i + 8]))
    return "{ \\\n" + ", \\\n".join(lines) + " \\\n}"


def main() -> None:
    qpro_dir = Path(__file__).resolve().parent
    human_dir = SIM_DIR / "human_data"

    bank = extract_vcv_acoustic_bank(DEFAULT_STIMULI_DIR)
    base_data = json.loads((human_dir / "human_listeners_98.json").read_text())
    bio_data = json.loads((human_dir / "biophysical_listeners_98.json").read_text())
    mnr_raw = json.loads((human_dir / "mnr_vcv_pta_model.json").read_text())

    base_listeners = base_data["listeners"]
    qcls_map = load_qcls_cochlear_profiles(base_listeners, DEFAULT_QCLS_MAT)
    elc_map, y_nh, cu5_sd, cu50_sd = load_raw_qcls_elc_matrix_map(DEFAULT_QCLS_MAT)
    norms, hp, self_off = build_clinical_norms(bank, base_listeners, bio_data, qcls_map, y_nh, cu5_sd, cu50_sd)

    n_mono = len(norms.ds_mono)

    # Single-struct static model header so both linked emcc/wasm-ld AND
    # single-TU clang --target=wasm32 share a single deterministic .rodata symbol:
    hdr = f"""/* Auto-generated by bake_qpro_model_h.py — DO NOT EDIT MANUALLY. */
#ifndef QPRO_MODEL_H
#define QPRO_MODEL_H

#define QPRO_N_STIM 10
#define QPRO_N_RESP 11
#define QPRO_N_FREQ 10
#define QPRO_N_CU 10
#define QPRO_N_MONO {n_mono}

typedef struct {{
    double aud_freqs_hz[10];
    double retspl_er3a[10];
    double retspl_legacy[10];
    double retspl_ansi[10];
    double ref_snr_db[10];
    double ltass_0snr_spl[10];
    double cue_spl[10 * 2 * 3 * 10];      /* [stim][tok][epoch][erb] */
    double vowel_spl[10 * 2 * 10];        /* [stim][tok][erb] */
    double voicing_acorr[10 * 2];         /* [stim][tok] */
    double continuant_idx[10 * 2];        /* [stim][tok] */
    double self_clarity_offset[10];
    double dir_choice_bias[10 * 10];      /* [stim][cand] */
    double y_nh_elc[10 * 10];             /* [freq][cu] */
    double y_nh_cu5_sd[10];
    double y_nh_cu50_sd[10];
    double nh_med_aud_hl[10];
    double nh_med_ohc_db[10];
    double ds_mono[{n_mono}];
    double pc_mono[{n_mono}];
    double gamma_ohc;
    double usom_vowel_att_db;
    double thr_offset_db;
    double spec_scale;
    double voice_scale;
    double cont_scale;
    double lapse_rate;
    double nh_med_unk;
    double pc_nh0;
    double nh_rtr_voicing;
    double nh_rtr_manner;
    double nh_rtr_place;
    double p90_total_db;
    double p95_total_db;
    double p90_aud_db;
    double p90_ohc_db;
    double p90_neural_db;
    double p95_neural_db;
    double nh_pc_p05;
    double nh_pc_median;
}} QProModelConst;

#define QPRO_MODEL_INIT {{ \\
    /* aud_freqs_hz */ \\
    {fmt_c_array_1d(AUD_FREQS_HZ, "{:.1f}")}, \\
    /* retspl_er3a */ \\
    {fmt_c_array_1d(RETSPL_TABLES["er3a"], "{:.2f}")}, \\
    /* retspl_legacy */ \\
    {fmt_c_array_1d(RETSPL_TABLES["legacy"], "{:.2f}")}, \\
    /* retspl_ansi */ \\
    {fmt_c_array_1d(ANSI_RETSPL_DB, "{:.2f}")}, \\
    /* ref_snr_db */ \\
    {fmt_c_array_1d(REF_SNR_ARR, "{:.2f}")}, \\
    /* ltass_0snr_spl */ \\
    {fmt_c_array_1d(bank.ltass_0snr_spl, "{:.5f}")}, \\
    /* cue_spl */ \\
    {fmt_c_array_1d(bank.cue_spl, "{:.5f}")}, \\
    /* vowel_spl */ \\
    {fmt_c_array_1d(bank.vowel_spl, "{:.5f}")}, \\
    /* voicing_acorr */ \\
    {fmt_c_array_1d(bank.voicing_acorr, "{:.6f}")}, \\
    /* continuant_idx */ \\
    {fmt_c_array_1d(bank.continuant_idx, "{:.6f}")}, \\
    /* self_clarity_offset */ \\
    {fmt_c_array_1d(self_off, "{:.6f}")}, \\
    /* dir_choice_bias */ \\
    {fmt_c_array_1d(hp.directional_choice_bias, "{:.6f}")}, \\
    /* y_nh_elc */ \\
    {fmt_c_array_1d(y_nh, "{:.4f}")}, \\
    /* y_nh_cu5_sd */ \\
    {fmt_c_array_1d(cu5_sd, "{:.4f}")}, \\
    /* y_nh_cu50_sd */ \\
    {fmt_c_array_1d(cu50_sd, "{:.4f}")}, \\
    /* nh_med_aud_hl */ \\
    {fmt_c_array_1d(norms.nh_ref_listener.cochlear_profile.audiogram_hl_db, "{:.4f}")}, \\
    /* nh_med_ohc_db */ \\
    {fmt_c_array_1d(norms.nh_ref_listener.cochlear_profile.hl_ohc_db, "{:.4f}")}, \\
    /* ds_mono */ \\
    {fmt_c_array_1d(norms.ds_mono, "{:.5f}")}, \\
    /* pc_mono */ \\
    {fmt_c_array_1d(norms.pc_mono, "{:.6f}")}, \\
    /* scalars */ \\
    {hp.gamma_ohc:.6f}, \\
    {hp.usom_vowel_att_db:.6f}, \\
    {hp.thr_offset_db:.6f}, \\
    {hp.spec_scale:.6f}, \\
    {hp.voice_scale:.6f}, \\
    {hp.cont_scale:.6f}, \\
    {hp.lapse_rate:.6f}, \\
    {norms.nh_ref_listener.unk_criterion:.6f}, \\
    {norms.pc_nh0:.6f}, \\
    {norms.nh_rtr_voicing:.6f}, \\
    {norms.nh_rtr_manner:.6f}, \\
    {norms.nh_rtr_place:.6f}, \\
    {norms.p90_total_db:.6f}, \\
    {norms.p95_total_db:.6f}, \\
    {norms.p90_aud_db:.6f}, \\
    {norms.p90_ohc_db:.6f}, \\
    {norms.p90_neural_db:.6f}, \\
    {norms.p95_neural_db:.6f}, \\
    {norms.nh_pc_p05:.6f}, \\
    {norms.nh_pc_median:.6f} \\
}}

#endif /* QPRO_MODEL_H */
"""
    (qpro_dir / "qpro_model.h").write_text(hdr)

    # Also bake the 6 featured qtest_dataset demo cases + full 98-listener test vectors for C parity tests:
    aided_by_hl: dict[str, dict[str, list[list[float]]]] = {}
    perf_mat_path = Path("/Users/neely/STN/2026_Quick_Tests/qtest_dataset/qVCV_analysis/QVC_perf.mat")
    if perf_mat_path.exists():
        mp = loadmat(str(perf_mat_path))
        ids_p = ["".join(ch).strip() for ch in mp["id"]]
        ccms_p = mp["ccms"]
        for idx_p, aid_id in enumerate(ids_p):
            if len(aid_id) >= 3 and aid_id.startswith(("HA", "HP")):
                hl_id = "HL" + aid_id[2:]
                aided_by_hl.setdefault(hl_id, {})[aid_id] = np.round(ccms_p[idx_p], 1).tolist()

    base_by_id = {r["listener_id"]: r for r in base_listeners}
    demo_specs = [
        ("NH013", "Case 1 — NH013: Normal Hearing & SIN Clarity"),
        ("HL045", "Case 2 — HL045: Clarity Loss w/ Normal Audiogram"),
        ("HL011", "Case 3 — HL011: Mild HF Loss + Marked Clarity Loss"),
        ("HL068", "Case 4 — HL068: Recruitment w/ Strong Aided Benefit (+24%)"),
        ("HL030", "Case 5 — HL030: Ski-Slope Recruitment + Aided Clarity Ceiling"),
        ("HL048", "Case 6 — HL048: Aided Rollover Alert (78.5% -> 68.0%)"),
    ]
    demos = []
    for sid, label in demo_specs:
        r = base_by_id[sid]
        prof = qcls_map[sid]
        elc = elc_map.get(sid)
        demos.append({
            "id": sid,
            "label": label,
            "group": r["archetype"],
            "ear": "Unspecified",
            "transducer": "er3a",
            "practice_pc": float(r["practice_pc"]),
            "audiogram_hl": np.round(prof.audiogram_hl_db, 1).tolist(),
            "elc_10x10": np.round(elc, 2).tolist() if elc is not None else None,
            "counts_s1": r["empirical_s1_counts"],
            "counts_s2": r["empirical_s2_counts"],
            "aided": aided_by_hl.get(sid, {}),
        })

    js_payload = {
        "demos": demos,
        "norms": {
            "y_nh_elc": np.round(y_nh, 2).tolist(),
            "y_nh_cu5_sd": np.round(cu5_sd, 2).tolist(),
            "y_nh_cu50_sd": np.round(cu50_sd, 2).tolist(),
            "retspl": {k: np.round(v, 2).tolist() for k, v in RETSPL_TABLES.items()},
            "p90_total_db": round(norms.p90_total_db, 2),
            "p95_total_db": round(norms.p95_total_db, 2),
            "p90_aud_db": round(norms.p90_aud_db, 2),
            "p90_ohc_db": round(norms.p90_ohc_db, 2),
            "p90_neural_db": round(norms.p90_neural_db, 2),
            "p95_neural_db": round(norms.p95_neural_db, 2),
            "nh_pc_p05": round(norms.nh_pc_p05, 1),
            "pc_nh0": round(norms.pc_nh0 * 100.0, 1),
        },
        "mnr_ppta": {k: np.round(np.array(mnr_raw[k], dtype=float), 5).tolist() for k in ("B", "C", "ca", "pa")},
    }
    (qpro_dir / "qpro_demo_cases.js").write_text(
        "// Auto-generated by bake_qpro_model_h.py\nwindow.QPRO_DATA = "
        + json.dumps(js_payload, separators=(",", ":"))
        + ";\n"
    )

    # Also write all 98 listeners' raw inputs to /tmp/qpro_parity_inputs_98.json for C/WASM parity validation:
    parity_vec = []
    for r in base_listeners:
        sid = r["listener_id"]
        prof = qcls_map[sid]
        elc = elc_map.get(sid)
        parity_vec.append({
            "listener_id": sid,
            "audiogram_hl": prof.audiogram_hl_db.tolist(),
            "has_qcls": bool(prof.has_measured_qcls),
            "elc_10x10": np.where(np.isnan(elc), -999.0, elc).tolist() if elc is not None else None,
            "practice_pc": float(r["practice_pc"]),
            "counts_s1": r["empirical_s1_counts"],
            "counts_s2": r["empirical_s2_counts"],
        })
    Path("/tmp/qpro_parity_inputs_98.json").write_text(json.dumps(parity_vec))
    print(f"Wrote {qpro_dir / 'qpro_model.h'} ({len(hdr)} bytes) and qpro_demo_cases.js ({len(demos)} demos).")


if __name__ == "__main__":
    main()
