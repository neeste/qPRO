def read_uleb(buf: bytes, pos: int) -> tuple[int, int]:
    res, shift = 0, 0
    while True:
        b = buf[pos]
        pos += 1
        res |= (b & 0x7F) << shift
        if not (b & 0x80):
            return res, pos
        shift += 7


def strip_custom_sections(wasm_bytes: bytes) -> bytes:
    assert wasm_bytes[:8] == b"\x00asm\x01\x00\x00\x00", "Invalid Wasm header"
    out = bytearray(wasm_bytes[:8])
    pos = 8
    while pos < len(wasm_bytes):
        sec_start = pos
        sec_id = wasm_bytes[pos]
        pos += 1
        sec_len, pos = read_uleb(wasm_bytes, pos)
        sec_end = pos + sec_len
        if sec_id != 0:
            out.extend(wasm_bytes[sec_start:sec_end])
        pos = sec_end
    return bytes(out)


